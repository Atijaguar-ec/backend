#!/usr/bin/env bash
# Version: 1.0.0
# Initializes /opt/inatrace directory structure, PostgreSQL Keycloak init script,
# docker-compose.yml manifest, and idempotent .env with high-entropy secrets.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "${SCRIPT_DIR}/lib/common.sh"

DOMAIN="trazabilidad.mi-cooperativa.org"
REALM="inatrace"
BASE_DIR="/opt/inatrace"
IMAGE_PREFIX="mi-organizacion"
IMAGE_TAG="v1.0.0"
SPRING_PROFILE="prod"
TLS_MODE="letsencrypt"
PG_PORT="5432"
FRONTEND_PORT="8081"
KEYCLOAK_PORT="8082"
BACKEND_PORT="8083"
FORCE_ENV="false"

usage() {
  cat <<'EOF'
Usage: 03-init-environment.sh [OPTIONS]

Initializes the INATrace deployment directory, PostgreSQL initdb script,
docker-compose.yml template, and encrypted high-entropy .env configuration.

Options:
  --domain <fqdn>          Public or LAN FQDN for the instance (required for real deployments)
  --realm <name>           Keycloak realm name (default: inatrace)
  --base-dir <path>        Base installation directory (default: /opt/inatrace)
  --image-prefix <prefix>  Container image prefix (default: mi-organizacion)
  --tag <tag>              Container image tag (default: v1.0.0)
  --spring-profile <prof>  Spring active profile (default: prod)
  --tls-mode <mode>        TLS mode recorded in .env: letsencrypt | lan-selfsigned (default: letsencrypt)
  --pg-port <port>         Localhost PostgreSQL port binding (default: 5432)
  --frontend-port <port>   Localhost Frontend container port (default: 8081)
  --keycloak-port <port>   Localhost Keycloak container port (default: 8082)
  --backend-port <port>    Localhost Backend container port (default: 8083)
  --force-env              Overwrite existing .env (rotates generated secrets)
  -h, --help               Show this help message and exit

Example:
  sudo ./03-init-environment.sh --domain trazabilidad.mi-cooperativa.org --image-prefix my-org --tag v1.0.0
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain)         [[ $# -ge 2 ]] || { log_error "--domain requires a value"; exit 1; }; DOMAIN="$2"; shift 2 ;;
    --realm)          [[ $# -ge 2 ]] || { log_error "--realm requires a value"; exit 1; }; REALM="$2"; shift 2 ;;
    --base-dir)       [[ $# -ge 2 ]] || { log_error "--base-dir requires a value"; exit 1; }; BASE_DIR="$2"; shift 2 ;;
    --image-prefix)   [[ $# -ge 2 ]] || { log_error "--image-prefix requires a value"; exit 1; }; IMAGE_PREFIX="$2"; shift 2 ;;
    --tag)            [[ $# -ge 2 ]] || { log_error "--tag requires a value"; exit 1; }; IMAGE_TAG="$2"; shift 2 ;;
    --spring-profile) [[ $# -ge 2 ]] || { log_error "--spring-profile requires a value"; exit 1; }; SPRING_PROFILE="$2"; shift 2 ;;
    --tls-mode)       [[ $# -ge 2 ]] || { log_error "--tls-mode requires a value"; exit 1; }; TLS_MODE="$2"; shift 2 ;;
    --pg-port)        [[ $# -ge 2 ]] || { log_error "--pg-port requires a value"; exit 1; }; PG_PORT="$2"; shift 2 ;;
    --frontend-port)  [[ $# -ge 2 ]] || { log_error "--frontend-port requires a value"; exit 1; }; FRONTEND_PORT="$2"; shift 2 ;;
    --keycloak-port)  [[ $# -ge 2 ]] || { log_error "--keycloak-port requires a value"; exit 1; }; KEYCLOAK_PORT="$2"; shift 2 ;;
    --backend-port)   [[ $# -ge 2 ]] || { log_error "--backend-port requires a value"; exit 1; }; BACKEND_PORT="$2"; shift 2 ;;
    --force-env)      FORCE_ENV="true"; shift ;;
    -h|--help)        usage; exit 0 ;;
    *)                log_error "Unknown option: $1"; usage >&2; exit 1 ;;
  esac
done

require_root
require_cmd openssl

for p in "${PG_PORT}" "${FRONTEND_PORT}" "${KEYCLOAK_PORT}" "${BACKEND_PORT}"; do
  [[ "${p}" =~ ^[0-9]+$ ]] || { log_error "Port must be numeric: ${p}"; exit 1; }
done

log_info "Creating INATrace runtime directories under ${BASE_DIR}..."
install -d -m 755 \
  "${BASE_DIR}" \
  "${BASE_DIR}/initdb" \
  "${BASE_DIR}/pg_data" \
  "${BASE_DIR}/file_storage" \
  "${BASE_DIR}/documents" \
  "${BASE_DIR}/keycloak-theme/inatrace"
install -d -m 700 "${BASE_DIR}/backups"

cp "${SCRIPT_DIR}/templates/initdb/01-create-keycloak-db.sh" "${BASE_DIR}/initdb/01-create-keycloak-db.sh"
chmod 755 "${BASE_DIR}/initdb/01-create-keycloak-db.sh"

cp "${SCRIPT_DIR}/templates/docker-compose.yml" "${BASE_DIR}/docker-compose.yml"
chmod 644 "${BASE_DIR}/docker-compose.yml"

ENV_PATH="${BASE_DIR}/.env"
if [[ ! -f "${ENV_PATH}" || "${FORCE_ENV}" == "true" ]]; then
  PG_PASS="$(openssl rand -hex 18)"
  KC_ADMIN_PASS="$(openssl rand -hex 18)"
  KC_CLIENT_SECRET="$(openssl rand -hex 24)"

  cat > "${ENV_PATH}" <<ENV_EOF
# INATrace Production Environment (generated by 03-init-environment.sh v1.1.0)
BASE_DIR=${BASE_DIR}
DOMAIN_NAME=${DOMAIN}
TLS_MODE=${TLS_MODE}
IMAGE_PREFIX=${IMAGE_PREFIX}
IMAGE_TAG=${IMAGE_TAG}
SPRING_PROFILES_ACTIVE=${SPRING_PROFILE}

# PostgreSQL 16
POSTGRES_DB=inatrace
POSTGRES_USER=inatrace_admin
POSTGRES_PASSWORD=${PG_PASS}
KC_DB_NAME=keycloak
PG_DATA_VOL=${BASE_DIR}/pg_data
PG_HOST_PORT=${PG_PORT}

# Internal container port bindings (localhost only)
FRONTEND_PORT=${FRONTEND_PORT}
KEYCLOAK_PORT=${KEYCLOAK_PORT}
BACKEND_PORT=${BACKEND_PORT}

# Keycloak 26 OIDC
KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=${KC_ADMIN_PASS}
KEYCLOAK_REALM=${REALM}
KEYCLOAK_CLIENT_ID=inatrace-backend
KEYCLOAK_CLIENT_SECRET=${KC_CLIENT_SECRET}
ENV_EOF
  chmod 600 "${ENV_PATH}"
  log_ok "Generated ${ENV_PATH} with mode 0600 and cryptographic secrets."
else
  log_warn "${ENV_PATH} already exists (preserving existing secrets). Pass --force-env to regenerate."
fi

log_ok "Environment initialized at ${BASE_DIR}."
